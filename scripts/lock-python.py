#!/usr/bin/env python3
"""Lock a requirements.in into a hash-pinned requirements.txt beside it.

    scripts/lock-python.py [--check] path/to/requirements.in [...]

Resolves with pip's own resolver (pip install --dry-run --report) for the
interpreter and platform the file declares, then records every file the index
holds for each pinned version (all wheels and the sdist), as
pip-compile --generate-hashes does, so the lock installs on any interpreter or
platform that resolves to the same versions. The image build installs with the
hashes, which makes pip refuse anything that does not match.

Directives, as comments in the .in file:

    # lock: python=3.13             interpreter to resolve for (required)
    # lock: constraint=other.txt    keep versions already pinned in another lock

--check exits 1 if a lock is out of date instead of rewriting it.
scripts/update-pins.sh runs this; Renovate's pip_requirements manager also
bumps the pins and their hashes in place.
"""
import argparse
import html
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.request

INDEX = os.environ.get(
    "PIP_INDEX_URL",
    "https://artifactory.cloud.cms.gov/artifactory/api/pypi/python/simple",
)
PLATFORMS = ["manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64", "linux_x86_64"]


def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def directives(path):
    found = {}
    with open(path) as f:
        for line in f:
            m = re.match(r"\s*#\s*lock:\s*(\w+)\s*=\s*(\S+)", line)
            if m:
                found[m.group(1)] = m.group(2)
    return found


def top_level(path, seen=None):
    """Requirement names declared in path and the files it includes with -r."""
    seen = seen if seen is not None else {}
    base = os.path.dirname(path)
    with open(path) as f:
        for raw in f:
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            if line.startswith(("-r ", "--requirement ")):
                top_level(os.path.join(base, line.split(None, 1)[1]), seen)
            elif not line.startswith("-"):
                m = re.match(r"[A-Za-z0-9][A-Za-z0-9._-]*", line)
                if m:
                    seen.setdefault(norm(m.group(0)), path)
    return seen


def resolve(in_path, python, constraint):
    major, minor = python.split(".")
    with tempfile.TemporaryDirectory() as tmp:
        report = os.path.join(tmp, "report.json")
        cmd = [
            sys.executable, "-I", "-m", "pip", "install", "--dry-run", "--ignore-installed",
            "--quiet", "--report", report, "--index-url", INDEX,
            "--python-version", python, "--implementation", "cp", "--abi", f"cp{major}{minor}",
            "--only-binary=:all:", "-r", in_path,
        ]
        for p in PLATFORMS:
            cmd += ["--platform", p]
        if constraint:
            # Constraints files may not carry hashes; pass the pins alone.
            pins = os.path.join(tmp, "constraints.txt")
            with open(constraint) as src, open(pins, "w") as dst:
                for line in src:
                    m = re.match(r"([A-Za-z0-9][A-Za-z0-9._-]*==\S+)", line)
                    if m:
                        dst.write(m.group(1) + "\n")
            cmd += ["-c", pins]
        subprocess.run(cmd, check=True)
        with open(report) as f:
            return json.load(f)["install"]


def index_hashes(name, version):
    page = urllib.request.urlopen(f"{INDEX}/{norm(name)}/", timeout=60).read().decode()
    stem = norm(name).replace("-", "[-_.]")
    hashes = set()
    for href in re.findall(r'href="([^"]+)"', page):
        href = html.unescape(href)
        m = re.search(r"#sha256=([0-9a-f]{64})", href)
        if not m:
            continue
        filename = href.split("#", 1)[0].rsplit("/", 1)[-1].lower()
        if re.match(rf"^{stem}-{re.escape(version.lower())}(-|\.tar\.gz$|\.zip$)", filename):
            hashes.add(m.group(1))
    return hashes


def render(in_path, python, installs):
    in_name = os.path.basename(in_path)
    declared = top_level(in_path)
    names = {norm(i["metadata"]["name"]) for i in installs}
    via = {n: set() for n in names}
    for item in installs:
        parent = norm(item["metadata"]["name"])
        for req in item["metadata"].get("requires_dist") or []:
            if ";" in req and "extra ==" in req:
                continue
            m = re.match(r"[A-Za-z0-9][A-Za-z0-9._-]*", req)
            if m and norm(m.group(0)) in via:
                via[norm(m.group(0))].add(parent)
    for name, source in declared.items():
        if name in via:
            via[name].add("-r " + os.path.relpath(source, os.path.dirname(in_path)))

    out = [
        f"# Generated by scripts/lock-python.py from {in_name} for Python {python}; do not edit.",
        "# Change the constraints in the .in file and run scripts/update-pins.sh --apply.",
        "",
    ]
    for item in sorted(installs, key=lambda i: norm(i["metadata"]["name"])):
        name, version = norm(item["metadata"]["name"]), item["metadata"]["version"]
        hashes = index_hashes(name, version)
        picked = item["download_info"]["archive_info"]["hashes"]["sha256"]
        if picked not in hashes:
            sys.exit(f"{in_path}: {name}=={version}: the resolved file is not on the index page")
        out.append(f"{name}=={version} \\")
        sorted_hashes = sorted(hashes)
        for n, h in enumerate(sorted_hashes):
            out.append(f"    --hash=sha256:{h}" + (" \\" if n < len(sorted_hashes) - 1 else ""))
        for parent in sorted(via[name], key=lambda v: (not v.startswith("-r"), v)):
            out.append(f"    # via {parent}")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("inputs", nargs="+")
    args = parser.parse_args()
    stale = False
    for in_path in args.inputs:
        if not in_path.endswith(".in"):
            sys.exit(f"{in_path}: expected a .in file")
        opts = directives(in_path)
        if "python" not in opts:
            sys.exit(f"{in_path}: missing '# lock: python=X.Y'")
        constraint = opts.get("constraint")
        if constraint:
            constraint = os.path.join(os.path.dirname(in_path), constraint)
        lock_path = in_path[: -len(".in")] + ".txt"
        text = render(in_path, opts["python"], resolve(in_path, opts["python"], constraint))
        current = open(lock_path).read() if os.path.exists(lock_path) else ""
        if text == current:
            print(f"{lock_path}: up to date")
        elif args.check:
            print(f"{lock_path}: out of date")
            stale = True
        else:
            with open(lock_path, "w") as f:
                f.write(text)
            print(f"{lock_path}: written")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
